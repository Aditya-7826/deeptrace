"""`deeptrace compare`: architecture and ablation tables from results/<run>/metrics.json."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from deeptrace.utils import load_yaml

NYM = "not yet measured"


def _fmt(v: float | None, digits: int = 3) -> str:
    return NYM if v is None else f"{v:.{digits}f}"


def _first(d: dict[str, Any]) -> tuple[str | None, dict[str, Any] | None]:
    return next(iter(d.items()), (None, None))


def load_results(results_dir: Path, runs: list[str]) -> dict[str, dict[str, Any] | None]:
    out = {}
    for run in runs:
        path = results_dir / run / "metrics.json"
        out[run] = json.loads(path.read_text(encoding="utf-8")) if path.exists() else None
    return out


def _jpeg50(m: dict[str, Any]) -> float | None:
    for lv in (m.get("robustness") or {}).get("families", {}).get("jpeg_quality", []):
        if lv["level"] == "q50":
            return lv["auc"]
    return None


def build_table(
    title: str, runs: dict[str, str], results: dict[str, dict | None], baseline: str | None = None
) -> str:
    cross_names = sorted({n for m in results.values() if m for n in m.get("cross_dataset", {})})
    head = ["Run", "In-dataset AUC [95% CI]"]
    head += [f"Cross AUC: {n}" for n in cross_names] or ["Cross-dataset AUC"]
    head += ["ECE (after T)", "AUC @ JPEG q50", "Uncertain rate"]
    if baseline:
        head.insert(2, "ΔAUC vs baseline")
    base_auc = None
    if baseline and results.get(baseline):
        base_auc = _first(results[baseline]["in_dataset"])[1]["auc"]
    lines = [f"## {title}", "", "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for run, label in runs.items():
        m = results.get(run)
        if m is None:
            cells = [f"{label} (`{run}`)"] + [NYM] * (len(head) - 1)
            lines.append("| " + " | ".join(cells) + " |")
            continue
        name, ind = _first(m["in_dataset"])
        if ind is None:
            auc_cell = NYM
        else:
            lo, hi = ind["auc_ci95"]
            auc_cell = f"{_fmt(ind['auc'])} [{_fmt(lo)}, {_fmt(hi)}] ({name})"
        cells = [f"{label} (`{run}`)", auc_cell]
        if baseline:
            delta = None if base_auc is None or ind is None else ind["auc"] - base_auc
            cells.append("baseline" if run == baseline else
                         (NYM if delta is None else f"{delta:+.3f}"))  # fmt: skip
        if cross_names:
            cells += [_fmt((m["cross_dataset"].get(n) or {}).get("auc")) for n in cross_names]
        else:
            cells.append(NYM)
        cells += [_fmt(ind and ind["ece_after"]), _fmt(_jpeg50(m)),
                  _fmt(ind and ind["uncertain_rate"])]  # fmt: skip
        lines.append("| " + " | ".join(cells) + " |")
    lines += ["", "Generated by `deeptrace compare` from `results/<run>/metrics.json`. "
              "Metrics are frame-level on the test split; the threshold and temperature "
              "were fitted on validation only.", ""]  # fmt: skip
    return "\n".join(lines)


def run_compare(results_dir: Path, groups_path: Path) -> dict[str, Path]:
    groups = load_yaml(groups_path)
    written = {}
    for key, fname in (("comparison", "comparison.md"), ("ablations", "ablations.md")):
        g = groups[key]
        runs = dict(g["runs"])
        results = load_results(results_dir, list(runs))
        text = build_table(g["title"], runs, results, g.get("baseline"))
        path = results_dir / fname
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written[key] = path
    if any(results_dir.glob("*/explain_sanity.json")):
        from deeptrace.explain.run import merge_sanity

        written["explain_sanity"] = merge_sanity(results_dir)
    return written
