"""Regenerate the README "Results" section from the files in results/.

PowerShell / bash:
    uv run python scripts/update_readme_results.py           # rewrite README.md
    uv run python scripts/update_readme_results.py --check   # exit 1 if README is stale (CI)

Only the text between the two marker comments is replaced. Every number comes from a
results file written by `deeptrace evaluate`, `export`, `benchmark`, `explain`, `compare`
or scripts/measure_api_memory.py. Anything missing is printed as "not yet measured".
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
START = "<!-- results:start (generated by scripts/update_readme_results.py; do not edit) -->"
END = "<!-- results:end -->"
NYM = "not yet measured"
# The run whose plots and calibration headline the README, best first.
HEADLINE_RUNS = ["effb0_main", "effb0_kaggle140k"]
DATASETS = {
    "ffpp": "FaceForensics++ c23",
    "celebdf": "Celeb-DF v2",
    "kaggle140k": "140k Real and Fake Faces (FFHQ vs StyleGAN)",
}
MODELS = {"pytorch_fp32": "PyTorch FP32", "onnx_fp32": "ONNX FP32", "onnx_int8": "ONNX INT8"}
PIPELINES = {
    "model_only": "model only (224×224 crop)",
    "end_to_end": "end to end (detect + crop + score)",
}
FAMILIES = {
    "jpeg_quality": "JPEG quality",
    "downscale": "Downscale",
    "gaussian_blur": "Gaussian blur",
    "screenshot": "Screenshot (resize + PNG)",
}


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _f(v: float | None, digits: int = 3) -> str:
    return NYM if v is None else f"{v:.{digits}f}"


def _auc_ci(m: dict[str, Any]) -> str:
    ci = m.get("auc_ci95") or [None, None]
    if m.get("auc") is None:
        return NYM
    if None in ci:
        return _f(m["auc"])
    return f"{m['auc']:.3f} [{ci[0]:.3f}, {ci[1]:.3f}]"


def _rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def metrics_runs(results: Path) -> dict[str, dict[str, Any]]:
    runs = {}
    for f in sorted(results.glob("*/metrics.json")):
        runs[f.parent.name] = json.loads(f.read_text(encoding="utf-8"))
    return runs


def headline(runs: dict[str, dict[str, Any]]) -> str | None:
    for name in HEADLINE_RUNS:
        if name in runs:
            return name
    return next(iter(runs), None)


def accuracy_section(runs: dict[str, dict[str, Any]]) -> list[str]:
    out = ["### In-dataset vs cross-dataset AUC", ""]
    if not runs:
        return out + [f"In-dataset AUC: {NYM}. Cross-dataset AUC: {NYM}.", ""]
    out += [
        "| Run | Trained on | Test set | Kind | Test images | AUC [95% CI] | Accuracy | F1 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    any_cross = False
    for name, m in runs.items():
        trained = ", ".join(DATASETS.get(d, d) for d in m.get("training_datasets", []))
        for kind, label in (("in_dataset", "in-dataset"), ("cross_dataset", "cross-dataset")):
            for ds, s in m.get(kind, {}).items():
                any_cross |= kind == "cross_dataset"
                out.append(
                    f"| `{name}` | {trained} | {DATASETS.get(ds, ds)} | {label} | {s['n']} "
                    f"| {_auc_ci(s)} | {_f(s.get('accuracy'))} | {_f(s.get('f1'))} |"
                )
    out.append("")
    gaps = [
        (n, k, v) for n, m in runs.items() for k, v in m.get("generalization_gap_auc", {}).items()
    ]
    if gaps:
        for name, pair, gap in gaps:
            src, dst = (DATASETS.get(p, p) for p in pair.split("->"))
            out.append(
                f"- **Generalization gap** (`{name}`): AUC drops by {gap:.3f} from {src} to {dst}."
            )
    if not any_cross:
        out.append(
            f"- **Cross-dataset AUC (Celeb-DF v2): {NYM}.** It needs the FaceForensics++ and "
            "Celeb-DF runs, which wait on dataset access."
        )
    out += [
        "",
        "AUC is frame-level on held-out test splits; the 95% interval is a bootstrap. "
        "The decision threshold and the calibration temperature were fitted on validation only.",
        "",
    ]
    return out


def calibration_section(runs: dict[str, dict[str, Any]], head: str | None, results: Path,
                        root: Path) -> list[str]:  # fmt: skip
    out = ["### Calibration", ""]
    if head is None:
        return out + [f"{NYM.capitalize()}.", ""]
    m = runs[head]
    c = m["calibration"]
    first = next(iter(m.get("in_dataset", {}).values()), {})
    lo, hi = c["uncertain_band"]
    rate = first.get("uncertain_rate")
    out += [
        f"`{head}`: temperature {c['temperature']:.3f}, decision threshold "
        f"{c['threshold']:.3f}, both fitted on {c['n_val']} validation images.",
        "",
        "| | ECE before | ECE after temperature scaling |",
        "|---|---|---|",
        f"| Validation | {_f(c.get('val_ece_before'))} | {_f(c.get('val_ece_after'))} |",
        f"| Test (in-dataset) | {_f(first.get('ece_before'))} | {_f(first.get('ece_after'))} |",
        "",
        f"Uncertain band {lo:.2f}–{hi:.2f}: "
        + (f"{rate:.1%} of in-dataset test images." if rate is not None else f"{NYM}."),
        "",
    ]
    png = results / head / "reliability.png"
    if png.exists():
        out += [f'<img src="{_rel(png, root)}" alt="Reliability diagram" width="520">', ""]
    return out


def robustness_section(runs: dict[str, dict[str, Any]], head: str | None, results: Path,
                       root: Path) -> list[str]:  # fmt: skip
    out = ["### Robustness", ""]
    rob = runs[head].get("robustness", {}) if head else {}
    fams = rob.get("families") or {}
    if not fams:
        return out + [f"{NYM.capitalize()}.", ""]
    test_set = DATASETS.get(rob.get("test_set"), rob.get("test_set"))
    out += [f"`{head}` on {rob.get('n')} {test_set} test images. AUC after each perturbation:", ""]
    out += ["| Perturbation | Levels (AUC) |", "|---|---|"]
    for fam, levels in fams.items():
        cells = ", ".join(f"{lv['level']}: {_f(lv['auc'])}" for lv in levels)
        out.append(f"| {FAMILIES.get(fam, fam)} | {cells} |")
    out.append("")
    png = results / head / "robustness.png"
    if png.exists():
        out += [f'<img src="{_rel(png, root)}" alt="Robustness curves" width="720">', ""]
    return out


def tables_section(results: Path) -> list[str]:
    out = []
    for fname, title in (
        ("comparison.md", "Architecture comparison"),
        ("ablations.md", "Ablations"),
    ):
        text = (results / fname).read_text(encoding="utf-8") if (results / fname).exists() else ""
        if text.strip():
            out += [line.replace("## ", "### ", 1) if line.startswith("## ") else line
                    for line in text.strip().splitlines()]  # fmt: skip
        else:
            out += [f"### {title}", "", f"{NYM.capitalize()}: needs the FaceForensics++ runs."]
        out.append("")
    return out


def export_line(results: Path, head: str | None) -> str:
    exp = _load(results / head / "export.json") if head else None
    if not exp:
        return f"- **INT8 quantization:** {NYM}."
    par = exp.get("parity", {})
    verdict = "passed" if par.get("passed") else "FAILED"
    parity = (f"ONNX vs PyTorch max |Δlogit| {par['max_abs_diff']:.1e} on {par['n']} images "
              f"(tolerance {par['tolerance']:.0e}, {verdict})")  # fmt: skip
    ok = [a for a in exp.get("int8_attempts", []) if a.get("accepted")]
    if ok:
        a = ok[0]
        q = (f"INT8 ({a['name']}) accepted: AUC drop {a['auc_drop']:.4f}, "
             f"agreement with FP32 {a['agreement']:.1%}")  # fmt: skip
    else:
        q = "INT8 rejected by the accuracy gate (AUC drop > 0.01), so FP32 ONNX is served"
    return f"- **Export:** {parity}. {q}."


def benchmark_section(results: Path, head: str | None) -> list[str]:
    out = ["### CPU latency and memory", ""]
    b = _load(results / "benchmark.json")
    if not b:
        out.append(f"Latency: {NYM}.")
    else:
        s, st = b["system"], b["settings"]
        out += [
            f"Measured on **{s['cpu']}** ({s['physical_cores']} cores, {s['ram_gb']} GB RAM, "
            f"{s['os']}), batch 1, {st['threads']} threads, {st['runs']} runs after "
            f"{st['warmup']} warm-up. Model `{b['model']['version']}`.",
            "",
            "| Model | Pipeline | p50 (ms) | p95 (ms) | Peak RSS (MB) |",
            "|---|---|---|---|---|",
        ]
        for r in b["results"]:
            model = MODELS.get(r["model"], r["model"])
            pipe = PIPELINES.get(r["pipeline"], r["pipeline"])
            out.append(
                f"| {model} | {pipe} | {r['p50_ms']:.1f} | {r['p95_ms']:.1f} "
                f"| {r['peak_rss_mb']:.0f} |"
            )
        if not any(r["model"] == "onnx_int8" for r in b["results"]):
            out += ["", "No INT8 rows: the INT8 model was not shipped (see the export line below)."]
    out.append("")
    out.append(export_line(results, head))
    mem = _load(results / "api_memory.json")
    if mem:
        verdict = "within" if mem.get("passed") else "OVER"
        out.append(
            f"- **API memory:** peak RSS {mem['peak_rss_mb']:.0f} MB across startup, "
            f"sequential and concurrent `/predict` and the first `/explain` ({verdict} the "
            f"{mem['limit_mb']:.0f} MB budget), measured by `scripts/measure_api_memory.py`."
        )
    else:
        out.append(f"- **API memory:** {NYM}.")
    return out + [""]


def gradcam_section(results: Path, head: str | None, root: Path) -> list[str]:
    out = ["### Grad-CAM", ""]
    sanity = _load(results / "explain_sanity.json") or {}
    s = (sanity.get("runs") or {}).get(head) if head else None
    if s:
        r, e = s["randomization_test"], s["energy"]
        out += [
            f"- **Model-randomization test** ({r['n']} images): mean |Spearman| between real and "
            f"randomized-weight heatmaps {r['mean_abs_spearman']:.2f} "
            f"({'passed' if r['passed'] else 'FAILED'}: maps depend on the learned weights).",
            f"- **Where the heat lands:** {e['mean_face_share']:.0%} face, "
            f"{e['mean_border_share']:.0%} crop border, "
            f"{e['mean_background_share']:.0%} background (mean over {e['n']} test crops).",
            "",
        ]
    else:
        out += [f"Sanity checks: {NYM}.", ""]
    gallery = [root / "docs" / "gradcam_gallery.png"]
    if head:
        gallery.append(results / head / "gradcam_gallery.png")
    png = next((p for p in gallery if p.exists()), None)
    if png:
        out += [f'<img src="{_rel(png, root)}" alt="Grad-CAM gallery: correct, wrong and '
                'uncertain predictions" width="720">', ""]  # fmt: skip
    else:
        out += [f"Gallery: {NYM}.", ""]
    return out


def render(results: Path, root: Path) -> str:
    runs = metrics_runs(results)
    head = headline(runs)
    lines = (
        accuracy_section(runs)
        + robustness_section(runs, head, results, root)
        + calibration_section(runs, head, results, root)
        + tables_section(results)
        + benchmark_section(results, head)
        + gradcam_section(results, head, root)
    )
    return "\n".join(lines).rstrip() + "\n"


def replace_block(readme: str, block: str) -> str:
    if readme.count(START) != 1 or readme.count(END) != 1:
        raise SystemExit("README must contain each results marker exactly once")
    head, rest = readme.split(START)
    _, tail = rest.split(END)
    return f"{head}{START}\n{block}{END}{tail}"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--readme", type=Path, default=ROOT / "README.md")
    ap.add_argument("--results", type=Path, default=ROOT / "results")
    ap.add_argument("--check", action="store_true", help="exit 1 if the README is out of date")
    args = ap.parse_args(argv)
    old = args.readme.read_text(encoding="utf-8")
    new = replace_block(old, render(args.results, args.readme.resolve().parent))
    if args.check:
        if new != old:
            print("README results section is stale: run scripts/update_readme_results.py")
            return 1
        print("README results section is up to date")
        return 0
    args.readme.write_text(new, encoding="utf-8", newline="\n")
    print(f"updated {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
